// Captures : four en panne et ruptures dans les réglages de la tablette (vague 3). Base locale, AUDIT_BASE=http://localhost:3228.
import { chromium } from "@playwright/test";
import { BASE, connecter } from "../audit/lib.mjs";

const nav = await chromium.launch({ channel: "chrome" });
const [nom, valeur] = (await connecter(process.env.COMPTE ?? "equipe-bureau@laferme.test")).split("=");
const ctx = await nav.newContext({ viewport: { width: 1180, height: 820 }, hasTouch: true });
await ctx.addCookies([{ name: nom, value: valeur, url: BASE }]);
const page = await ctx.newPage();
await page.goto(`${BASE}/tablette`);
await page.getByRole("button", { name: "Continuer sans son" }).click();
await page.getByRole("button", { name: "Pause, délai, ruptures" }).click();
const bloc = page.locator(".tab-pannes");
await bloc.getByRole("button", { name: "Four en panne" }).click();
await page.screenshot({ path: "docs/rendus/vague-3/tablette/panne-confirmer-1180.png" });
await bloc.getByRole("button", { name: "Jusqu'à ce soir" }).click();
await bloc.getByRole("button", { name: "Remettre en vente", disabled: false }).waitFor();
await bloc.locator(".tab-touchees").waitFor();
await page.waitForFunction(() => ![...document.querySelectorAll(".tab-pannes button")].some((b) => b.disabled));
await page.screenshot({ path: "docs/rendus/vague-3/tablette/panne-four-1180.png" });
await page.getByLabel("Chercher un plat ou un supplément").fill("marg");
await page.locator(".tab-rupture-motif", { hasText: "Four en panne" }).first().scrollIntoViewIfNeeded();
await page.screenshot({ path: "docs/rendus/vague-3/tablette/panne-plats-1180.png" });
await page.getByLabel("Chercher un plat ou un supplément").fill("");
await bloc.getByRole("button", { name: "Remettre en vente" }).click();
await bloc.getByRole("button", { name: "Four en panne" }).waitFor();
await bloc.getByRole("button", { name: "Une catégorie…" }).click();
await page.screenshot({ path: "docs/rendus/vague-3/tablette/panne-categorie-1180.png" });
await bloc.getByRole("button", { name: "Une catégorie…" }).click();
// Choix obligatoire : épuiser tous les choix de pâtes sauf un, puis le dernier demande confirmation.
await page.getByLabel("Chercher un plat ou un supplément").fill("");
const pates = page.locator(".tab-groupe-options", { has: page.locator("h4", { hasText: "choix obligatoire" }) }).first();
const boutons = pates.getByRole("button", { name: "Disponible" });
const n = await boutons.count();
for (let i = 0; i < n - 1; i++) await boutons.first().click(), await page.waitForTimeout(400);
await pates.getByRole("button", { name: "Disponible" }).first().click();
await pates.locator(".tab-confirmation").scrollIntoViewIfNeeded();
await page.screenshot({ path: "docs/rendus/vague-3/tablette/panne-dernier-choix-1180.png" });
await pates.getByRole("button", { name: "Annuler" }).click();
for (const b of await pates.getByRole("button", { name: "Épuisé" }).all()) await b.click(), await page.waitForTimeout(400);
await nav.close();
console.log("captures faites", n);
